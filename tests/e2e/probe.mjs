import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { chromium } = require('playwright');
import { createServer } from 'vite';
const server = await createServer({ root: '/home/user/hollowacres', server: { port: 5198 }, logLevel: 'error' });
await server.listen();
const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: 960, height: 540 } });
page.on('pageerror', (e) => console.log('pageerror', e.message));
page.on('console', (m) => { if (m.type() === 'error' || m.type() === 'warning') console.log('console', m.type(), m.text().slice(0, 300)); });
await page.goto('http://localhost:5198/');
await page.waitForSelector('.menu-btn');
const gl = await page.evaluate(() => { const c = document.createElement('canvas'); const g = c.getContext('webgl2'); const d = g.getExtension('WEBGL_debug_renderer_info'); return d ? g.getParameter(d.UNMASKED_RENDERER_WEBGL) : 'n/a'; });
console.log('GL', gl);
await page.click('text=New farm'); await page.click('text=Begin');
await page.waitForFunction(() => window.__HA && window.__HA.state === 'paused' && window.__HA.renderer, null, { timeout: 180000 });
await page.click('text=Click to begin');
const r = await page.evaluate(() => new Promise((res) => { const a = window.__HA; const t0 = performance.now(); let n = 0; const f = () => { n++; if (n < 6) requestAnimationFrame(f); else res({ msPerFrame: (performance.now() - t0) / 5, stats: a.renderer.stats, fps: a.fps }); }; requestAnimationFrame(f); }));
console.log(JSON.stringify(r));
await browser.close(); await server.close();
